-- Delta seguro para tabelas de adubação de culturas em bancos PostgreSQL legados.
-- A versão V20260619_01 já existe neste repositório para VALOR_MAXIMO_ESPACAMENTO_USADO;
-- por isso este delta usa a próxima versão Flyway disponível.

ALTER TABLE TABELAS_ADUBACAO_CULTURAS
    ADD COLUMN IF NOT EXISTS ID_PROPRIEDADE BIGINT,
    ADD COLUMN IF NOT EXISTS ID_TALHAO BIGINT,
    ADD COLUMN IF NOT EXISTS ID_EXTRATO_ANALISE_FISICA BIGINT,
    ADD COLUMN IF NOT EXISTS ID_EXTRATO_ANALISE_FERTILIDADE BIGINT,
    ADD COLUMN IF NOT EXISTS CRITERIO_DE_CALAGEM INTEGER;

CREATE TABLE IF NOT EXISTS DOSES_MICRONUTRIENTES_TABELAS_ADUBACAO_CULTURAS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TABELA_ADUBACAO_CULTURA BIGINT NOT NULL,
    MICRONUTRIENTE VARCHAR(10) NOT NULL,
    DOSE_MINIMA DOUBLE PRECISION NOT NULL,
    DOSE_MAXIMA DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_TABELAS_ADUBACAO_CULTURAS_PROPRIEDADE
    ON TABELAS_ADUBACAO_CULTURAS (ID_PROPRIEDADE);

CREATE INDEX IF NOT EXISTS IDX_TABELAS_ADUBACAO_CULTURAS_TALHAO
    ON TABELAS_ADUBACAO_CULTURAS (ID_TALHAO);

CREATE INDEX IF NOT EXISTS IDX_TABELAS_ADUBACAO_CULTURAS_ANALISE_FISICA
    ON TABELAS_ADUBACAO_CULTURAS (ID_EXTRATO_ANALISE_FISICA);

CREATE INDEX IF NOT EXISTS IDX_TABELAS_ADUBACAO_CULTURAS_ANALISE_FERTILIDADE
    ON TABELAS_ADUBACAO_CULTURAS (ID_EXTRATO_ANALISE_FERTILIDADE);

CREATE INDEX IF NOT EXISTS IDX_DOSES_MICRONUTRIENTES_TABELA_ADUBACAO
    ON DOSES_MICRONUTRIENTES_TABELAS_ADUBACAO_CULTURAS (ID_TABELA_ADUBACAO_CULTURA);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('FK_TABELAS_ADUBACAO_CULTURAS_PROPRIEDADE')
    ) THEN
        ALTER TABLE TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT FK_TABELAS_ADUBACAO_CULTURAS_PROPRIEDADE
            FOREIGN KEY (ID_PROPRIEDADE) REFERENCES PROPRIEDADES(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('FK_TABELAS_ADUBACAO_CULTURAS_TALHAO')
    ) THEN
        ALTER TABLE TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT FK_TABELAS_ADUBACAO_CULTURAS_TALHAO
            FOREIGN KEY (ID_TALHAO) REFERENCES TALHOES(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('FK_TABELAS_ADUBACAO_CULTURAS_ANALISE_FISICA')
    ) THEN
        ALTER TABLE TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT FK_TABELAS_ADUBACAO_CULTURAS_ANALISE_FISICA
            FOREIGN KEY (ID_EXTRATO_ANALISE_FISICA) REFERENCES EXTRATOS_ANALISES_FISICAS(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('FK_TABELAS_ADUBACAO_CULTURAS_ANALISE_FERTILIDADE')
    ) THEN
        ALTER TABLE TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT FK_TABELAS_ADUBACAO_CULTURAS_ANALISE_FERTILIDADE
            FOREIGN KEY (ID_EXTRATO_ANALISE_FERTILIDADE) REFERENCES EXTRATOS_ANALISES_FERTILIDADE(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('FK_DOSES_MICRONUTRIENTES_TABELA_ADUBACAO')
    ) THEN
        ALTER TABLE DOSES_MICRONUTRIENTES_TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT FK_DOSES_MICRONUTRIENTES_TABELA_ADUBACAO
            FOREIGN KEY (ID_TABELA_ADUBACAO_CULTURA) REFERENCES TABELAS_ADUBACAO_CULTURAS(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE lower(conname) = lower('UK_DOSE_MICRONUTRIENTE_TABELA_ADUBACAO')
    ) THEN
        ALTER TABLE DOSES_MICRONUTRIENTES_TABELAS_ADUBACAO_CULTURAS
            ADD CONSTRAINT UK_DOSE_MICRONUTRIENTE_TABELA_ADUBACAO
            UNIQUE (ID_TABELA_ADUBACAO_CULTURA, MICRONUTRIENTE);
    END IF;
END $$;
